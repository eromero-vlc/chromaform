  --test-colorvecs[=yes|no]  (re)do the tests for distillation basis
  --test-mesons[=yes|no]     (re)do the tests for mesons
  --test-baryons[=yes|no]    (re)do the tests for baryons
  --test-props[=yes|no]      (re)do the tests for props
  --test-genprops[=yes|no]   (re)do the tests for genprops
  --test-eigenvalues[=yes|no] (re)do the tests for computing eigenvectors
  --test-disco[=yes|no]      (re)do the tests for disconnected loops
  --test-corr[=yes|no]       (re)do the tests for correlation functions

Options for the tests:
  --dims="Lx Ly Lz Lt"       lattice size
  --num-vecs=N               distillation basis rank
  --try-local[=yes|no]       generate baryons, props and genprops on multiple files
  --redstar-version=VERSION  redstar XML version (12 or 14)
  --num-procs=N              number of processes
  --geom="gx gy gz gt"       number of processes on each lattice direction

Miscellaneous options:
  --help                     show this help message and exit

Recommended chroma installations:
./chromaform --superb redstardl chroma        # for cpu
./chromaform --superb redstardl chroma --hip  # for hip/rocm
./chromaform --superb redstardl chroma --cuda # for cuda

Recommended laplace_eigs, harom, chroma (single precision), and redstar installations:
./chromaform laplace_eigs
./chromaform --float harom chroma
./chromaform --superb redstar
EOF
}

# Check commandline arguments
for ((i = 1; i <= ${#}; ++i)); do
    arg="${!i}"
    case $arg in
        --help | -h) show_help && exit 0 ;;
        # Options for the directories
        --chromaform-dir=*) chromaform="$(realpath ${arg#--chromaform-dir=})" ;;
        --adat-dir=*) adat="$(realpath ${arg#--adat-dir=})" ;;
        --redstar-dir=*) redstar="$(realpath ${arg#--redstar-dir=})" ;;
        --arch=cpu) arch=cpu ;;
        --arch=hip) arch=hip ;;
        --arch=cuda) arch=cuda ;;
        # Options for the binary paths
        --laplace_eigs=*) laplace_eigs="$(realpath ${arg#--laplace_eigs=})" ;;
        --harom=*) harom="$(realpath ${arg#--harom=})" ;;
        --dbutil=*) dbutil="$(realpath ${arg#--dbutil=})" ;;
        --storage_details=*) storage_details="$(realpath ${arg#--storage_details=})" ;;
        --chroma=*) chroma="$(realpath ${arg#--chroma=})" ;;
        --chroma_single=*) chroma_single="$(realpath ${arg#--chroma_single=})" ;;
        --redstar_corr_graph=*) redstar_corr_graph="$(realpath ${arg#--redstar_corr_graph=})" ;;
        --redstar_npt=*) redstar_npt="$(realpath ${arg#--redstar_npt=})" ;;
        # Options for what to test
        --test-colorvecs-against-laplace_eigs=yes) check_eigs_against_laplace_eigs=yes ;;
        --test-colorvecs-against-laplace_eigs) check_eigs_against_laplace_eigs=yes ;;
        --test-colorvecs-against-laplace_eigs=no) check_eigs_against_laplace_eigs=nop ;;
        --test-colorvecs=yes) do_eigs=yes ;;
        --test-colorvecs) do_eigs=yes ;;
        --test-colorvecs=no) do_eigs=nop ;;
        --test-mesons=yes) do_mesons=yes ;;
        --test-mesons) do_mesons=yes ;;
        --test-mesons=no) do_mesons=nop ;;
        --test-baryons=yes) do_baryons=yes ;;
        --test-baryons) do_baryons=yes ;;
        --test-baryons=no) do_baryons=nop ;;
        --test-props=yes) do_props=yes ;;
        --test-props) do_props=yes ;;
        --test-props=no) do_props=nop ;;
        --test-genprops=yes) do_gprops=yes ;;
        --test-genprops) do_gprops=yes ;;
        --test-genprops=no) do_gprops=nop ;;
        --test-eigenvalues=yes) do_eigenvalues=yes ;;
        --test-eigenvalues) do_eigenvalues=yes ;;
        --test-eigenvalues=no) do_eigenvalues=nop ;;
        --test-disco=yes) do_disco=yes ;;
        --test-disco) do_disco=yes ;;
        --test-disco=no) do_disco=nop ;;
        --test-corr=yes) do_redstar=yes ;;
        --test-corr) do_redstar=yes ;;
        --test-corr=no) do_redstar=nop ;;
        # Options for the tests
        --dims=*) dims="${arg#--dims=}" ;;
        --num-vecs=*) num_vecs="${arg#--num-vecs=}" ;;
        --try-local-storage=yes) try_local=yes ;;
        --try-local) try_local=yes ;;
        --try-local=no) try_local=nop ;;
        --redstar-version=*) redstar_version="${arg#--redstar-version=}" ;;
        --num-procs=*) num_procs="${arg#--num-procs=}" ;;
        --geom=*) chroma_geom="${arg#--geom=}" ;;
        *)
            echo "error: invalid option ${arg}"
            exit 1
            ;;
    esac
done

# Check the required components
[ $do_eigs != yes ] && check_eigs_against_laplace_eigs="nop"
laplace_eigs_needed=nop
[ $check_eigs_against_laplace_eigs == yes ] && laplace_eigs_needed="yes"
harom_needed=nop
[ $check_eigs_against_laplace_eigs == yes ] && harom_needed="yes"
chroma_single_needed=nop
[ $check_eigs_against_laplace_eigs == yes ] && chroma_single_needed="yes"
chroma_needed=nop
[ $do_eigs == yes -o $do_mesons == yes -o $do_baryons == yes -o $do_props == yes -o $do_gprops == yes -o $do_eigenvalues == yes -o $do_disco == yes -o $do_redstar == yes ] && chroma_needed="yes"
redstar_needed=nop
[ $do_redstar == yes ] && redstar_needed=yes

#Set defaults
[ "z$chromaform" != z -a "z$adat" == z ] && adat="$chromaform/install/adat-superbblas"
[ "z$chromaform" != z -a "z$redstar" == z ] && redstar="$chromaform/install/redstar-colorvec-hadron-cpu-adat-superbblas"
[ "z$chromaform" != z -a "z$laplace_eigs" == z ] && laplace_eigs="$chromaform/install/laplace_eigs-qdpxx-double-nd3/laplace_eigs"
[ "z$chromaform" != z -a "z$harom" == z ] && harom="$chromaform/install/harom-qdpxx-single-nd3-cpu/bin/harom"
[ "z$adat" != z -a "z$dbutil" == z ] && dbutil="$adat/bin/dbutil"
[ "z$chromaform" != z -a "z$storage_details" == z ] && storage_details="$chromaform/src/superbblas/tests/storage_details"
if [ "z$storage_details" != z ] && [ ! -f $storage_details -a -d $(dirname $storage_details) ]; then
    make - C $(dirname $storage_details) storage_details
fi
if [ "z$chromaform" != z -a "z$chroma" == z ]; then
    case $arch in
        cpu) chroma="$chromaform/install/chroma-qdpxx-double-nd4-redstardl-superbblas-cpu/bin/chroma" ;;
        hip) chroma="$chromaform/install/chroma-sp-qdp-jit-double-nd4-cmake-redstardl-superbblas-hip//bin/chroma" ;;
        cuda) chroma="$chromaform/install/chroma-sp-qdp-jit-double-nd4-cmake-redstardl-superbblas-cuda/bin/chroma" ;;
    esac
fi
[ "z$chromaform" != z -a "z$chroma_single" == z ] && chroma_single="$chromaform/install/chroma-qdpxx-single-nd4/bin/chroma"
[ "z$redstar" != z -a "z$redstar_corr_graph" == z ] && redstar_corr_graph="$redstar/bin/redstar_corr_graph"
[ "z$redstar" != z -a "z$redstar_npt" == z ] && redstar_npt="$redstar/bin/redstar_npt"
[ "z$chroma_geom" == z ] && chroma_geom="1 1 1 $num_procs"

# Check that all the required components exists
if [ $laplace_eigs_needed == yes ] && [ "z$laplace_eigs" == z -o ! -f $laplace_eigs ]; then
    echo "Missing laplace_eigs, path set to $laplace_eigs"
    exit 1
fi
if [ $harom_needed == yes ] && [ "z$harom" == z -o ! -f $harom ]; then
    echo "Missing harom, path set to $harom"
    exit 1
fi
if [ "z$dbutil" == z -o ! -f $dbutil ]; then
    echo "Missing dbutil, path set to $dbutil"
    exit 1
fi
if [ "z$storage_details" == z -o ! -f $storage_details ]; then
    echo "Missing storage_details, path set to $storage_details"
    exit 1
fi
if [ $chroma_needed == yes ] && [ "z$chroma" == z -o ! -f $chroma ]; then
    echo "Missing chroma, path set to $chroma"
    exit 1
fi
if [ $chroma_single_needed == yes ] && [ "z$chroma_single" == z -o ! -f $chroma_single ]; then
    echo "Missing chroma_single, path set to $chroma_single"
    exit 1
fi
if [ $redstar_needed == yes ] && [ "z$redstar_corr_graph" == z -o ! -f $redstar_corr_graph ]; then
    echo "Missing redstar_corr_graph, path set to $redstar_corr_graph"
    exit 1
fi
if [ $redstar_needed == yes ] && [ "z$redstar_npt" == z -o ! -f $redstar_npt ]; then
    echo "Missing redstar_npt, path set to $redstar_npt"
    exit 1
fi

# Set auxiliary variables
t_size="$(echo $dims | awk '{print $4}')"
spatial_size="$(echo $dims | awk '{print $1, $2, $3}')"
do_phasings="nop yes"
[ $redstar_version -ge 14 ] && do_phasings="nop yes mix"
[ "z$t_source" == z ] && t_source="$((t_size - 1))"

# Set env for chroma to perform better
export SB_NUM_GPUS_ON_NODE=1
export OMP_NUM_THREADS=1
export OPENBLAS_NUM_THREADS=1
extra="-geom $chroma_geom -by 2 -bz 2 -pxy 1 -pxyz 1 -c 1 -sy 1 -sz 1 -poolsize 0k  -pool-max-alloc 0  -pool-max-alignment 512 -libdevice-path /opt/rocm/core/lib/llvm/amdgcn/bitcode -libdevice-name hip.bc"
export SB_DEBUG=0
#export SB_TRACK_MEM=1

MPIRUN="mpirun -np $num_procs --oversubscribe"
debug="$MPIRUN st -e gdb --args"
tmpf="$(mktemp)"
all_tests_ok="yes"
run() {
    msg="$1"
    shift
    echo -n $msg "... "
    echo "$>" "$@" >$tmpf
    "$@" </dev/null >>$tmpf 2>&1
    last_status=$?
    # FIXME! remove the double free
    if [ $last_status -ne 0 ] && ! grep -q "double free or corruption" $tmpf &>/dev/null; then
        all_tests_ok="nop"
        echo "-- last command failed with exit status $last_status"
        cat $tmpf
        return $last_status
    fi
    echo OK
    return 0
}

neg_mom() {
    echo $((-$1)) $((-$2)) $((-$3))
}

workdir="out_dims${dims// /_}_mass${prop_mass}_clover${prop_clover}_nvec${num_vecs}"
[ $redstar_version -ge 14 ] && workdir+=".reg"
mkdir -p ${workdir}
cd ${workdir}

fermaction="
          <FermionAction>
            <FermAct>CLOVER</FermAct>
            <Mass>${prop_mass}</Mass>
            <clovCoeff>${prop_clover}</clovCoeff>
            <Stabilized>false</Stabilized>
            <FermState>
              <Name>STOUT_FERM_STATE</Name>
              <rho>0.125</rho>
              <n_smear>1</n_smear>
              <orthog_dir>-1</orthog_dir>
              <FermionBC>
                <FermBC>SIMPLE_FERMBC</FermBC>
                <boundary>1 1 1 -1</boundary>
              </FermionBC>
            </FermState>
          </FermionAction>
"

cnfparam="
 <RNG>
  <Seed>
    <elem>11</elem>
    <elem>11</elem>
    <elem>11</elem>
    <elem>0</elem>
  </Seed>
</RNG>

 <Cfg>
 <cfg_type>DISORDERED</cfg_type>
 <cfg_file>dummy</cfg_file>
 </Cfg>
"
smearing_content="
    <LinkSmearingType>STOUT_SMEAR</LinkSmearingType>
    <link_smear_fact>0.1</link_smear_fact>
    <link_smear_num>10</link_smear_num>
    <no_smear_dir>3</no_smear_dir>
"
smearing="
  <LinkSmearing>$smearing_content
  </LinkSmearing>
"

solver_old="
            <invType>BICGSTAB_INVERTER</invType>
            <RsdBiCGStab>1.0e-7</RsdBiCGStab>
            <MaxBiCGStab>20000</MaxBiCGStab>
            <Verbose>true</Verbose>
"
solver_new="${solver_old}"

# Print options and plan
echo dims= $dims num_vecs= $num_vecs phase= $phase Nt= $Nt
echo dir= $workdir
echo -n "tasks:"
[ $do_eigs == yes ] && echo -n " colorvecs"
[ $do_mesons == yes ] && echo -n " mesons"
[ $do_baryons == yes ] && echo -n " baryons"
[ $do_props == yes ] && echo -n " props"
[ $do_gprops == yes ] && echo -n " genprops"
[ $do_eigenvalues == yes ] && echo -n " eigenvalues"
[ $do_redstar == yes ] && echo -n " corr"
echo

# Create eigenvectors

eigfile="eigs"
if [ $do_eigs == yes ]; then
    echo "### Testing colorvecs"
    for action in "write_fingerprint=true" "write_fingerprint=false" "phase"; do
        eigsxml="eig-${action}.xml"
        write_fingerprint="false"
        [ $action == "write_fingerprint=true" ] && write_fingerprint="true"
        [ $action == "write_fingerprint=true" ] && eigf="$eigfile.s3t"
        [ $action == "write_fingerprint=false" ] && eigf="$eigfile.mod"
        [ $action == "phase" ] && eigf="$eigfile-phase.mod"
        cat <<EOF >$eigsxml
<chroma>
<Param>
  <InlineMeasurements>
    <elem>
      <Name>CREATE_COLORVECS_SUPERB</Name>
      <Frequency>1</Frequency>
      <Param>
        <num_vecs>$num_vecs</num_vecs>
        <decay_dir>3</decay_dir>
        <write_fingerprint>${write_fingerprint}</write_fingerprint>
    $(
            [ $action == phase ] && echo "<phase>$phase</phase>"
        )
        $smearing
      </Param>
      <NamedObject>
        <gauge_id>default_gauge_field</gauge_id>
        <colorvec_out>$eigf</colorvec_out>
    $(
            [ $write_fingerprint == "false" ] && echo "<colorvec_files><elem>${eigfile}.s3t</elem></colorvec_files>"
        )
      </NamedObject>
    </elem>
  </InlineMeasurements>
  <nrow>$dims</nrow>
</Param>
$cnfparam
</chroma>
EOF
        rm -f $eigf
        run "Testing generating colorvecs with $action" $MPIRUN $chroma -i $eigsxml $extra
        [ $action == "write_fingerprint=true" -a -f $storage_details ] && run "Checking eigenvector file ${eigfile}.s3t" $storage_details ${eigfile}.s3t

    done # write_fingerprint
fi       # do_eigs

# Write gauge
if [ $check_eigs_against_laplace_eigs == "yes" -o $check_against_harom == "yes" ]; then
    cat <<EOF >gauge.xml
<chroma>
<Param>
  <InlineMeasurements>
    <elem>
      <Name>LINK_SMEAR</Name>
      <Frequency>1</Frequency>
      <Param>
      $smearing_content
      </Param>
      <NamedObject>
        <gauge_id>default_gauge_field</gauge_id>
        <linksmear_id>stout_gauge_field</linksmear_id>
      </NamedObject>
    </elem>
    <elem>
      <Name>WRITE_TIMESLICE_MAP_OBJECT_DISK</Name>
      <NamedObject>
        <object_type>ArrayLatticeColorMatrix</object_type>
        <input_id>default_gauge_field</input_id>
        <output_file>gauge.mod</output_file>
      </NamedObject>
    </elem>
    <elem>
      <Name>WRITE_TIMESLICE_MAP_OBJECT_DISK</Name>
      <NamedObject>
        <object_type>ArrayLatticeColorMatrix</object_type>
        <input_id>stout_gauge_field</input_id>
        <output_file>stout.mod</output_file>
      </NamedObject>
    </elem>
  </InlineMeasurements>
  <nrow>$dims</nrow>
</Param>
$cnfparam
</chroma>
EOF
    if [ ! -f gauge.mod ]; then
        rm -f stout.mod
        run "Writing gauge files" $chroma_single -i gauge.xml
    fi
fi

# Compare laplace_eigs with chroma create colorvecs

if [ $check_eigs_against_laplace_eigs == "yes" ]; then
    for t_slice in $(seq 0 $((t_size - 1))); do
        cat <<EOF >laplace_eigs.xml
<?xml version="1.0"?>
<LaplaceEigs>
  <Param>
    <version>2</version>
    <Layout>$spatial_size</Layout>
    <LinearOperator>Laplacian</LinearOperator>
    <t_slice>$t_slice</t_slice>
    <gauge_file>stout.mod</gauge_file>
    <vec_file>${eigfile}-t_${t_slice}.mod</vec_file>
  </Param>
  <EigenInfo>
    <Nev>$num_vecs</Nev>
    <PrintLevel>3</PrintLevel>
    <LambdaC>0.5</LambdaC>
    <LambdaMax>15</LambdaMax>
    <NCheb>-1</NCheb>
    <Tol>1e-06</Tol>
  </EigenInfo>
</LaplaceEigs>
EOF
        [ ! -f ${eigfile}-t_${t_slice}.mod ] && run "Running laplace_eigs" $laplace_eigs laplace_eigs.xml laplace_eigs_t_${t_slice}.out
    done # t_slice

    cat <<EOF >${eigfile}-compare.xml
<chroma>
<Param>
  <InlineMeasurements>
    <elem>
      <Name>CREATE_COLORVECS_SUPERB</Name>
      <Frequency>1</Frequency>
      <Param>
        <num_vecs>$num_vecs</num_vecs>
        <decay_dir>3</decay_dir>
        <write_fingerprint>true</write_fingerprint>
        $smearing
      </Param>
      <NamedObject>
        <gauge_id>default_gauge_field</gauge_id>
        <colorvec_out>${eigfile}-compare.s3t</colorvec_out>
        <colorvec_files>
    $(
        for t_slice in $(seq 0 $((t_size - 1))); do
            echo "<elem>${eigfile}-t_${t_slice}.mod</elem>"
        done
    )
        </colorvec_files>
      </NamedObject>
    </elem>
  </InlineMeasurements>
  <nrow>$dims</nrow>
</Param>
$cnfparam
</chroma>
EOF
    rm -f ${eigfile}-compare.s3t
    run "Comparing chroma and laplace_eigs colorvecs" $MPIRUN $chroma -i ${eigfile}-compare.xml $extra
fi

# Mesons
if [ $do_mesons == yes ]; then
    formats="old"
    [ $meson_new_format == yes ] && formats="old new"
    for format in $formats; do
        for phasing in $do_phasings; do
            [ $phasing == mix -a $format == old ] && continue
            this_eigfile="$eigfile.s3t"
            [ $format == old -a $phasing == yes ] && this_eigfile="$eigfile-phase.mod"
            for part in $(if [ $phasing == mix ]; then echo a b; else echo a; fi); do
                echo "### Testing mesons with phasing=$phasing"
                param="
      <Param>
        <version>4</version>
        <use_derivP>true</use_derivP>
        <use_superb_format>$(if [ $format == old ]; then echo false; else echo true; fi)</use_superb_format>
        <t_source>$t_source</t_source>
        <Nt_forward>$((Nt))</Nt_forward>
        <mom2_min>0</mom2_min>
        <mom2_max>2</mom2_max>
        <max_tslices_in_contraction>1</max_tslices_in_contraction>
        <mom_list>
                <elem>0 0 0</elem>
