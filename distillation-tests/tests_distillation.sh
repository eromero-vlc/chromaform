#!/bin/bash

## Ultimate script to test superb tasks at chroma.
## In particular, it tests
## - distillation vectors produced by chroma's CREATE_COLORVECS_SUPERB are the same as laplace_eigs
## - mesons produced by chroma's MESON_MATELEM_COLORVEC_SUPERB are the same as harom's MESON_MATELEM_COLORVEC.
## - baryons produced by chroma's BARYON_MATELEM_COLORVEC_SUPERB are the same as harom's BARYON_MATELEM_COLORVEC_OPT.
## - props produced by chroma's PROP_AND_MATELEM_DISTILLATION_SUPERB are the same as chroma's PROP_AND_MATELEM_DISTILLATION.
## - genprops produced by chroma's UNSMEARED_HADRON_NODE_DISTILLATION_SUPERB are the same as chroma's UNSMEARED_HADRON_NODE_DISTILLATION.
## - disconnected loops produced by chroma's DISCO_PROBING_DEFLATION_SUPERB and DISCO_PROBING_3D_DEFLATION_SUPERB are the same as chroma's DISCO_PROBING_DEFLATION
## - correlation functions produced by chroma's CORR_SUPERB are the same as redstar
##
## Theses tests are combined with other tests:
## - Using filehash versus superb storage of distillation vectors, meson, baryons, props, and genprops.
## - Storing the full distillation vectors versus storing a subset
## - Storing baryon, prop and genprops on multiple files (XML's option output_file_is_local)
## - Using momentum boosting (phasing)
## - Redstar changes on the input XML from version 12 to 14
##
## NOTE: format with `shfmt -i 4 -ci -bn -s -w tests_distillation.sh`

# Directories
chromaform="" # path to chromaform installation
adat=""       # path to adat installation
redstar=""    # path to redstar installation
arch="cpu"    # chromaform architecture installation (either cpu, hip or cuda)

# Binary paths
laplace_eigs=""       # path the laplace_eigs binary
harom=""              # path to the harom binary in single precision
dbutil=""             # path to adat's dbutil binary
storage_details=""    # path to superbblas's storage_details binary
chroma=""             # path to chroma binary
chroma_single=""      # path to chroma binary for single precision
redstar_corr_graph="" # path to redstar's redstar_corr_graph
redstar_npt=""        # path to redstar's redstar_npt

# What tests to do
check_eigs_against_laplace_eigs="nop" # whether to check the distillation vectors produced by chroma against the ones produced by laplace_eigs (requires laplace_eigs and chroma_single)
check_against_harom="nop"             # whether to check meson and baryons generated by chroma against the ones produced by harom (requires harom and chroma_single)
do_eigs="yes"                         # whether to (re)do the tests for distillation basis
do_mesons="yes"                       # whether to (re)do the tests for mesons
do_baryons="yes"                      # whether to (re)do the tests for baryons
do_props="yes"                        # whether to (re)do the tests for props
do_gprops="yes"                       # whether to (re)do the tests for genprops
do_eigenvalues="nop"                  # whether to (re)do the tests for computing eigenvectors
do_disco="nop"                        # whether to (re)do the tests for disconnected loops
do_redstar="yes"                      # whether to (re)do the test for correlation functions

# Options about tests
dims="2 2 2 4"         # lattice size
num_vecs="4"           # distillation basis rank
phase="0 0 1"          # test phase
neg_phase="0 0 -1"     # negation of the test phase
prop_mass="-0.1"       # prop mas
prop_clover="1"        # prop clover
try_local="yes"        # generate baryons, props and genprops on multiple files
meson_new_format="yes" # whether to test meson new format
num_procs=1            # number of processes
chroma_geom=""         # number of processes on each lattice direction
chroma_extra=""        # chroma extra arguments
redstar_version=14     # redstar XML version either (12 or 14)
Nt=3                   # redstar correlation timeslices
t_source=""            # time-slice source

show_help() {
    cat <<'EOF'
Usage: tests_distillation.sh [options]

Options for the directories:
  --chromaform-dir=DIR       path to the chromaform installation
  --arch=[cpu|hip|cuda]      architecture used in chromaform installation
  --adat-dir=DIR             path to the adat installation
  --redstar-dir=DIR          path to the redstar installation

Options for the binary paths:
  --laplace_eigs=PATH        path to the laplace_eigs binary
