  --storage_details=PATH     path to superbblas's storage_details binary
  --chroma=PATH              path to the chroma binary
  --chroma_single=PATH       path to the chroma binary for single precision
  --redstar_corr_graph=PATH  path to redstar's redstar_corr_graph
  --redstar_npt=PATH         path to redstar's redstar_npt

Options for what to test:
  --test-colorvecs-against-laplace_eigs[=yes|no]
